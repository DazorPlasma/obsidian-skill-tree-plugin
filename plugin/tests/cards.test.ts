import assert from "node:assert/strict";
import test from "node:test";

import { isSpacedRepetitionDeck, readCardMaturities } from "../src/cards.ts";

test("only counts cards assigned to the default flashcards deck", () => {
  const note = "What owns this?::A value";
  assert.deepEqual(readCardMaturities(note, false), []);
  assert.equal(isSpacedRepetitionDeck(note, { tags: ["flashcards"] }), true);
  assert.equal(isSpacedRepetitionDeck("#flashcards/rust\n\n" + note, undefined), true);
});

test("recognizes default basic, reversed, multiline, and highlighted cloze cards", () => {
  const note = [
    "#flashcards",
    "Q1::A1",
    "",
    "Q2:::A2",
    "",
    "Front of a multiline card",
    "?",
    "Back of a multiline card",
    "",
    "Front of a reversed multiline card",
    "??",
    "Back of the reversed card",
    "",
    "Rust is ==safe== by default",
    "",
    "```markdown",
    "not::a card",
    "```",
  ].join("\n");
  const maturities = readCardMaturities(note, true);
  assert.equal(maturities.length, 7);
  assert.deepEqual(maturities, Array(7).fill("immature"));
});

test("reads OSR and FSRS intervals using the upstream 32-day maturity cutoff", () => {
  const note = [
    "#flashcards",
    "SM2::A",
    "<!--SR:!2026-08-01,32,250-->",
    "FSRS::A",
    "<!--SR:!fsrs,2026-08-01T00:00:00.000Z,31,31,5,2,3,0,0,2026-07-01T00:00:00.000Z-->",
    "Old::A",
    "<!--SR:2000-01-01,100,250-->",
    "",
    "Legacy::A",
    "<!--SR:2026-08-01,21,250-->",
  ].join("\n");
  assert.deepEqual(readCardMaturities(note, true), ["mature", "immature", "immature", "immature"]);
});

test("unknown or malformed scheduling data remains unknown", () => {
  const note = [
    "#flashcards",
    "Broken::A",
    "<!--SR:!not-a-date,99,250-->",
    "FSRS::A",
    "<!--SR:!fsrs,2026-08-01T00:00:00.000Z,45,31,5,8,3,0,0,2026-07-01T00:00:00.000Z-->",
    "Truncated::A",
    "<!--SR:!fsrs,2026-08-01T00:00:00.000Z,45-->",
  ].join("\n");
  assert.deepEqual(readCardMaturities(note, true), ["unknown", "unknown", "unknown"]);
});

test("maps separate sibling schedules to their card siblings", () => {
  const note = [
    "#flashcards",
    "Left:::Right",
    "<!--SR:!2026-08-01,40,250!2026-08-01,12,250-->",
  ].join("\n");
  assert.deepEqual(readCardMaturities(note, true), ["mature", "immature"]);
});

test("counts every card generated by a multi-cloze paragraph", () => {
  const note = [
    "#flashcards",
    "Rust is ==safe== by default and has ==ownership== rules.",
    "<!--SR:!2026-08-01,40,250!2026-08-01,12,250-->",
  ].join("\n");
  assert.deepEqual(readCardMaturities(note, true), ["mature", "immature"]);
});

test("keeps code blocks inside multiline cards and attaches their schedule", () => {
  const note = [
    "#flashcards",
    "What does this example print?",
    "?",
    "```rust",
    "fn main() { println!(\"hello\"); }",
    "```",
    "<!--SR:!2026-08-01,40,250-->",
  ].join("\n");
  assert.deepEqual(readCardMaturities(note, true), ["mature"]);
});

test("reads multiline scheduling comments attached to inline cards", () => {
  const note = [
    "#flashcards",
    "Inline::Answer",
    "<!--SR:",
    "!2026-08-01,40,250",
    "-->",
  ].join("\n");
  assert.deepEqual(readCardMaturities(note, true), ["mature"]);
});

test("empty numeric schedule fields are unknown", () => {
  const note = [
    "#flashcards",
    "SM2::A",
    "<!--SR:!2026-08-01,,250-->",
    "FSRS::A",
    "<!--SR:!fsrs,2026-08-01T00:00:00.000Z,,31,5,2,3,0,0,2026-07-01T00:00:00.000Z-->",
  ].join("\n");
  assert.deepEqual(readCardMaturities(note, true), ["unknown", "unknown"]);
});
